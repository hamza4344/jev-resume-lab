def test_coverage_gives_half_credit_for_partial():
    criteria={k:Criterion(score=80) for k in WEIGHTS}
    partial='Built FastAPI and Python APIs, using Docker with REST APIs.\nWrote SQL reporting services.\nImplemented CI pipelines.'
    none='Built FastAPI and Python APIs, using Docker with REST APIs.\nWrote SQL reporting services.'
    full=partial+'\nImplemented automated production deployments.'
    part_score,_,_,_=combined_scores(criteria,partial,ROLE,JD)
    none_score,_,_,_=combined_scores(criteria,none,ROLE,JD)
    full_score,_,_,_=combined_scores(criteria,full,ROLE,JD)
    assert none_score < part_score < full_score
    # Each component is worth half of one of six required skills.
    assert round(part_score-none_score,2)==round(0.45*100*0.5/6,2)


def test_partial_skill_contributes_to_bullet_ranking():
    text='Implemented authentication and CI pipelines for backend services.'
    score,full,related=semantic_relevance(text,ROLE,JD,[])
    assert score >= 20
    assert 'CI/CD' not in full
    bullets=[{'id':0,'entry_id':'experience-1','text':text,'role':'Python Engineer'}]
    result=rank_bullets(bullets,ROLE,JD)[0]
    assert result['relevance_evidence']['required_skills']==[]
    assert result['relevance_evidence']['partial_required_skills']==['CI/CD']


def test_api_offline_returns_three_nonoverlapping_status_lists(monkeypatch):
    monkeypatch.delenv('BEATAPI_API_KEY',raising=False)
    monkeypatch.delenv('APP_API_KEY',raising=False)
    payload=b'''SUMMARY
Backend engineer shipping Python services.
SKILLS
Python, FastAPI, REST APIs, PostgreSQL, Docker, AWS, Celery, pytest, Git.
EXPERIENCE
Python Engineer | Riverton Commerce | 2022 - Present
- Implemented authentication, background queues, monitoring alerts, and CI pipelines.
- Built FastAPI REST APIs using Python.
- Deployed services with Docker.
- Maintained SQL reporting services.
'''
    response=TestClient(app).post('/api/review', files={'file':('resume.txt',payload,'text/plain')},
                     data={'target_role':ROLE,'job_description':JD})
    assert response.status_code==200, response.text
    body=response.json()
    assert body['matching_skills']==['Python','FastAPI','Docker','REST APIs','SQL']
    assert body['partial_required_skills']==['CI/CD']
    assert body['missing_required_skills']==[]
    assert body['unmet_required_skills']==['CI/CD']
    item=next(d for d in body['skill_evidence'] if d['skill']=='CI/CD')
    assert item['status']=='partially_demonstrated'
    assert item['unverified_components']==['CD']
    assert set(body['matching_skills']).isdisjoint(body['partial_required_skills'])
    assert set(body['matching_skills']).isdisjoint(body['missing_required_skills'])



"""Compound requirement QA: CI and CD are distinct, auditable claims.

These fixtures are fictional and do not establish candidate proficiency.
"""
import io
from pathlib import Path

import pytest
from fastapi.testclient import TestClient
from app.main import (app, Criterion, WEIGHTS, combined_scores,
                      skill_details, semantic_relevance, rank_bullets)

JD = 'Required: Python, FastAPI, Docker, REST APIs, SQL, CI/CD.'
ROLE = 'Python Backend Engineer'


def detail(resume, jd=JD, name='CI/CD'):
    matches = [x for x in skill_details(resume, ROLE, jd) if x['skill'] == name]
    assert len(matches) == 1
    return matches[0]


def test_actual_backend_resume_ci_only():
    resume = '''SUMMARY
Backend engineer with four years delivering web APIs.
SKILLS
Python, FastAPI, REST APIs, PostgreSQL, Docker, AWS, Celery, pytest, Git.
EXPERIENCE
Python Engineer | Riverton Commerce | Mar 2022 - Present
- Built FastAPI microservices for order processing.
- Implemented authentication, background queues, monitoring alerts, and CI pipelines.
- Deployed Docker containers to AWS ECS.
Software Developer | Oakline | Jun 2020 - Feb 2022
- Maintained Python data sync jobs and SQL reporting services.
'''
    found = {x['skill']: x for x in skill_details(resume, ROLE, JD)}
    assert [x['skill'] for x in found.values() if x['status'] == 'matched'] == ['Python', 'FastAPI', 'Docker', 'REST APIs', 'SQL']
    ci = found['CI/CD']
    assert ci['status'] == 'partially_demonstrated'
    assert ci['demonstrated_components'] == ['CI']
    assert ci['unverified_components'] == ['CD']
    assert ci['component_evidence']['CI'] == ['Implemented authentication, background queues, monitoring alerts, and CI pipelines.']
    assert ci['component_evidence']['CD'] == []


@pytest.mark.parametrize('claim,expected_status,parts', [
    ('Implemented CI pipelines.', 'partially_demonstrated', ['CI']),
    ('Configured continuous integration builds.', 'partially_demonstrated', ['CI']),
    ('Implemented CD pipelines.', 'partially_demonstrated', ['CD']),
    ('Automated production deployments.', 'partially_demonstrated', ['CD']),
    ('Built CI/CD workflows for build, test and deployment.', 'matched', ['CI','CD']),
    ('Implemented CI pipelines and release pipelines.', 'matched', ['CI','CD']),
    ('Configured continuous integration and continuous deployment.', 'matched', ['CI','CD']),
    ('Implemented CI pipelines but no CD pipelines.', 'partially_demonstrated', ['CI']),
    ('Built CI/CD pipelines but did not implement CD.', 'partially_demonstrated', ['CI']),
    ('Built CI/CD pipelines but did not implement CI.', 'partially_demonstrated', ['CD']),
    ('Did not implement CI or CD.', 'not_demonstrated', []),
    ('Only used artifacts generated by other teams CI/CD processes, did not implement CI or CD.', 'not_demonstrated', []),
    ('Used reports generated by another team from their CI/CD automation.', 'not_demonstrated', []),
    ('I am currently learning about CI/CD.', 'not_demonstrated', []),
    ('Built backend APIs but did not create any CI/CD pipelines.', 'not_demonstrated', []),
])
def test_ci_cd_component_detection(claim, expected_status, parts):
    assert detail(claim)['status'] == expected_status
    assert detail(claim)['demonstrated_components'] == parts


